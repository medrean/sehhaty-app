/**
 * 🔗 إعدادات الربط باللوحة المركزية (SaaS Hub)
 * ==================================================================
 * ⚠️ هذا الملف هو **المصدر الوحيد** لعنوان اللوحة المركزية في كل الموقع:
 *    تطبيق React (الرئيسية) + صفحات الدفع والتحقق (bill / otp / pin ...).
 *
 * ──────────────────────────────────────────────────────────────────
 * 🚀 عند نشر الموقع على نطاق مختلف عن اللوحة (Render / Vercel / أي استضافة):
 *    اكتب هنا رابط اللوحة المرفوعة **كاملاً**.
 *
 *    window.SAAS_HUB_URL = "https://my-panel.onrender.com";
 *
 * ✅ وإن كانت اللوحة نفسها هي التي تقدّم الموقع (نفس النطاق) → اتركه فارغاً.
 * ✅ ويعمل تلقائياً على http://localhost:5000 أثناء التطوير المحلي.
 * ──────────────────────────────────────────────────────────────────
 */
// ✅ عنوان لوحة التحكم المركزية المنشورة — يُضبط مرة واحدة هنا ويسري على الموقع كله
// (يمكن لاحقاً ضبطها من خارج الملف — لا تُصفّر إن كانت معرّفة مسبقاً)
window.SAAS_HUB_URL = window.SAAS_HUB_URL || "https://panel-back.onrender.com";

/**
 * يحدّد عنوان اللوحة الفعلي بالترتيب:
 *   1) القيمة المكتوبة في SAAS_HUB_URL أعلاه (إن وُجدت)
 *   2) localhost:5000 أثناء التطوير المحلي
 *   3) نفس نطاق الموقع — حين تقدّم اللوحة الموقع بنفسها
 */
window.SAAS_RESOLVE_HUB_URL = function () {
    var configured = String(window.SAAS_HUB_URL || "").trim().replace(/\/+$/, "");
    if (configured) return configured;

    var host = window.location.hostname;
    var isLocal = !host || host === "localhost" || host === "127.0.0.1";
    return isLocal ? "http://localhost:5000" : window.location.origin;
};
